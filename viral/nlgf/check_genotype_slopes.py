import sys
from pathlib import Path

HERE = Path(__file__).parent
sys.path.append(str(HERE.parent.parent))

import numpy as np
import pandas as pd
from viral.nlgf.paths import RESULTS
from viral.nlgf.style import GENOTYPE_ORDER

d = pd.read_csv(RESULTS / "spatial_stability.csv")
d = d[d.genotype.isin(GENOTYPE_ORDER)]

for col in ["field_corr_cross", "pv_corr_cross"]:
    rows = []
    for g in GENOTYPE_ORDER:
        s = d[d.genotype == g].dropna(subset=[col, "gap_days"])
        slope = (
            np.polyfit(s.gap_days, s[col], 1)[0]
            if len(s) > 2 and s.gap_days.nunique() > 1
            else np.nan
        )
        rows.append(
            dict(
                genotype=g,
                slope_per_day=slope,
                pairs=len(s),
                mice=s.mouse.nunique(),
                gap_mean=s.gap_days.mean(),
                gap_min=s.gap_days.min(),
                gap_max=s.gap_days.max(),
                gaps=dict(s.gap_days.value_counts().sort_index()),
            )
        )
    t = pd.DataFrame(rows)
    print(f"\n=== {col} ===")
    print(t.round(4).to_string(index=False))

    # the slope each option would apply
    two = t[t.genotype.isin(["WT", "NLGF"])]
    ok = d.dropna(subset=[col, "gap_days"])
    gc = ok.gap_days - ok.groupby("genotype").gap_days.transform("mean")
    vc = ok[col] - ok.groupby("genotype")[col].transform("mean")
    print(f"A  WT+NLGF mean:          {two.slope_per_day.mean():+.4f}")
    print(f"B  all three, equal:      {t.slope_per_day.mean():+.4f}")
    print(f"C  pooled within-group:   {(gc * vc).sum() / (gc ** 2).sum():+.4f}")
