"""Where registered pairs drop out on the way to spatial_stability.csv.

Generated by Claude (Opus 5.5, medium effort) on 30/10/2026.

Every matches_*.csv passes three filters before it becomes a row of
spatial_stability.csv, and none of them reports what it drops:

    registration_qc.py      usable = n_matched >= MIN_MATCHED and
                            affine_rms_px <= MAX_AFFINE_RMS
    spatial_stability.py    pair_stability() returns None, silently, if
                              - fewer than N_POOL matches lie within
                                MAX_CELL_RESIDUAL px of the affine fit
                              - spks or the cached session JSON is missing
                              - either day has fewer than N_LAPS imaged laps
    staleness               a CSV built before later pairs were registered or
                            before QC was re-run does not contain them

This repeats those checks for every match table, without building any place-field
maps, and gives each pair the first reason it would be dropped:

    in table                                 present in spatial_stability.csv
    not in registration_qc.csv               QC is older than this match table
    QC fail                                  too few matches or affine RMS too high
    <N_POOL matches within MAX_CELL_RESIDUAL residual filter leaves too few cells
    cached session json or spks missing
    <N_LAPS imaged laps
    passes every check                       should be in the table: it is stale

Reads only. Writes stability_funnel.csv to RESULTS (overwritten on each run).

    python -m viral.nlgf.stability_funnel
"""

from __future__ import annotations

import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).parent
sys.path.append(str(HERE.parent.parent))

from viral.imaging_utils import trial_is_imaged  # noqa: E402
from viral.models import Cached2pSession  # noqa: E402
from viral.nlgf.cross_session import MAX_CELL_RESIDUAL, N_POOL  # noqa: E402
from viral.nlgf.paths import CACHED_2P, RESULTS, spks_path  # noqa: E402
from viral.nlgf.registration_qc import (  # noqa: E402
    MAX_AFFINE_RMS,
    MIN_MATCHED,
    _centroids,
    _fit_affine,
)
from viral.nlgf.spatial_stability import N_LAPS  # noqa: E402
from viral.utils import get_genotype  # noqa: E402

_laps_cache: dict = {}


def imaged_laps(mouse: str, date: str) -> int:
    """Imaged laps counted as spatial_stability._lap_maps counts them; -1 if no JSON."""
    key = (mouse, date)
    if key not in _laps_cache:
        p = CACHED_2P / f"{mouse}_{date}.json"
        if not p.exists():
            _laps_cache[key] = -1
        else:
            session = Cached2pSession.model_validate_json(p.read_text())
            n = 0
            for t in session.trials:
                try:
                    n += bool(trial_is_imaged(t))
                except (AssertionError, IndexError):
                    pass
            _laps_cache[key] = n
    return _laps_cache[key]


def funnel() -> pd.DataFrame:
    for name in ("registration_qc.csv", "spatial_stability.csv",
                 "registration_diagnostics.csv"):
        p = RESULTS / name
        print(f"{name:32s}", time.ctime(p.stat().st_mtime) if p.exists() else "MISSING")
    print(f"N_POOL={N_POOL}  MAX_CELL_RESIDUAL={MAX_CELL_RESIDUAL}  N_LAPS={N_LAPS}  "
          f"MIN_MATCHED={MIN_MATCHED}  MAX_AFFINE_RMS={MAX_AFFINE_RMS}\n")

    qc_path, st_path = RESULTS / "registration_qc.csv", RESULTS / "spatial_stability.csv"
    qc = pd.read_csv(qc_path, dtype={"date_a": str, "date_b": str}) \
        if qc_path.exists() else pd.DataFrame(columns=["mouse", "date_a", "date_b"])
    st = pd.read_csv(st_path, dtype={"date_a": str, "date_b": str}) \
        if st_path.exists() else pd.DataFrame(columns=["mouse", "date_a", "date_b"])
    qc_rows = {(r.mouse, r.date_a, r.date_b): r for r in qc.itertuples()}
    in_stability = set(zip(st.mouse, st.date_a, st.date_b))

    rows = []
    for f in sorted(RESULTS.glob("matches_*.csv")):
        if f.name.startswith("._"):
            continue
        parts = f.stem[len("matches_"):].split("_")
        if len(parts) != 3:
            continue
        mouse, a, b = parts
        key = (mouse, a, b)
        try:
            genotype = get_genotype(mouse)
        except ValueError:
            genotype = "unknown"
        q = qc_rows.get(key)
        row = dict(
            mouse=mouse, genotype=genotype, date_a=a, date_b=b,
            gap_days=(pd.to_datetime(b) - pd.to_datetime(a)).days,
            in_qc=q is not None,
            usable=bool(q.usable) if q is not None and hasattr(q, "usable") else False,
            n_matched=getattr(q, "n_matched", np.nan),
            affine_rms_px=getattr(q, "affine_rms_px", np.nan),
            in_stability=key in in_stability,
        )
        if key in in_stability:
            row["reason"] = "in table"
        elif q is None:
            row["reason"] = "not in registration_qc.csv (QC older than match table?)"
        elif not row["usable"]:
            row["reason"] = (f"QC fail (<{MIN_MATCHED} matched or affine RMS "
                             f">{MAX_AFFINE_RMS})")
        else:
            m = pd.read_csv(f)
            # same as pair_stability: if the affine fit fails, the filter is skipped
            try:
                ca, cb = _centroids(mouse, a), _centroids(mouse, b)
                if m.row_a.max() < len(ca) and m.row_b.max() < len(cb):
                    _, resid = _fit_affine(ca[m.row_a.to_numpy()],
                                           cb[m.row_b.to_numpy()])
                    n_kept = int((resid <= MAX_CELL_RESIDUAL).sum())
                else:
                    n_kept = len(m)
            except Exception:  # noqa: BLE001
                n_kept = len(m)
            la, lb = imaged_laps(mouse, a), imaged_laps(mouse, b)
            row.update(n_after_residual=n_kept, laps_a=la, laps_b=lb)
            if n_kept < N_POOL:
                row["reason"] = f"<{N_POOL} matches within {MAX_CELL_RESIDUAL}px"
            elif min(la, lb) < 0 or not (spks_path(mouse, a).exists()
                                         and spks_path(mouse, b).exists()):
                row["reason"] = "cached session json or spks missing"
            elif min(la, lb) < N_LAPS:
                row["reason"] = f"<{N_LAPS} imaged laps"
            else:
                row["reason"] = "passes every check - table is stale"
        rows.append(row)
    return pd.DataFrame(rows)


def main() -> None:
    f = funnel()
    if f.empty:
        sys.exit(f"no match tables in {RESULTS}")
    out = RESULTS / "stability_funnel.csv"
    f.to_csv(out, index=False)

    print(f"{len(f)} match tables, {f.mouse.nunique()} mice\n")
    print("=== pairs: reason x genotype ===")
    print(pd.crosstab(f.reason, f.genotype, margins=True).to_string())
    print("\n=== mice: in table vs any pair registered ===")
    mice = f.groupby("genotype").agg(
        registered=("mouse", "nunique"),
        in_table=("mouse", lambda s: s[f.loc[s.index, "in_stability"]].nunique()),
    )
    print(mice.to_string())
    print(f"\nwritten {out}")


if __name__ == "__main__":
    main()
