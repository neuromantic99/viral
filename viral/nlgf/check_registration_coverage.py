"""Which ROICaT pairs should exist, and which silently didn't happen.

Generated by Claude (Opus 5.5, medium effort) on 30/10/2026.

register_roicat.build_pairs() builds the pair list from the cohort FIRST and only then
drops pairs whose stat/ops/iscell files are missing, printing a single count. In
"consecutive" mode that means one session without suite2p output removes BOTH of its
neighbouring pairs (prev -> it, it -> next) and no bridging pair (prev -> next) is ever
created, so that stretch of the timeline has no registration at all. Pairs that were
attempted but crashed are also only visible in the run log (the loop catches the
exception and moves on).

This rebuilds the expected pair list exactly as build_pairs does, without the file
filter, and checks each pair against what is on disk:

    registered        match table exists
    no_suite2p        never attempted: stat/ops/iscell missing for one or both days
    failed            files present but no match table -> crashed, or never run
    no_diagnostics    match table exists but the pair is missing from
                      registration_diagnostics.csv (run interrupted after the CSV write)
    never_generated   (bridge pairs only) build_pairs never created this pair

plus the "bridge" pairs: consecutive pairs over sessions that DO have suite2p output,
which would cover the gap left by a missing session but were never generated.

Run with the project venv (does not import roicat):

    python -m viral.nlgf.check_registration_coverage
    python -m viral.nlgf.check_registration_coverage --dff /path/to/dff --results /path/to/results

Writes registration_coverage.csv next to the match tables.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).parent
sys.path.append(str(HERE.parent.parent))

from viral.nlgf import paths  # noqa: E402
from viral.nlgf.cohort import sessions  # noqa: E402

SUITE2P_FILES = ("stat", "ops", "iscell")  # same as register_roicat


def _missing(dff: Path, mouse: str, date: str) -> list[str]:
    return [k for k in SUITE2P_FILES if not (dff / f"{mouse}_{date}_{k}.npy").exists()]


def coverage(dff: Path, results: Path, min_cells: int, genotypes=None) -> tuple:
    d = sessions(
        min_cells=min_cells, stages=["learning", "reversal"], genotypes=genotypes
    )
    d = d.copy()
    d["when"] = pd.to_datetime(d.date)
    d = d.sort_values(["mouse", "when"]).reset_index(drop=True)
    d["missing_files"] = [
        ",".join(_missing(dff, r.mouse, r.date)) for r in d.itertuples()
    ]
    d["has_suite2p"] = d.missing_files == ""

    diag_path = results / "registration_diagnostics.csv"
    in_diag = set()
    if diag_path.exists():
        dg = pd.read_csv(diag_path, dtype=str)
        in_diag = set(zip(dg.mouse, dg.date_a, dg.date_b))

    rows = []

    def add(kind, mouse, genotype, a, b):
        key = (mouse, a.date, b.date)
        has_csv = (results / f"matches_{mouse}_{a.date}_{b.date}.csv").exists()
        bad = [f"{x.date}({x.missing_files})" for x in (a, b) if not x.has_suite2p]
        if has_csv:
            status = "registered" if key in in_diag else "no_diagnostics"
        elif bad:
            status = "no_suite2p"
        elif kind == "bridge":
            status = "never_generated"
        else:
            status = "failed"
        rows.append(
            dict(
                kind=kind,
                mouse=mouse,
                genotype=genotype,
                date_a=a.date,
                date_b=b.date,
                gap_days=(b.when - a.when).days,
                status=status,
                sessions_missing_suite2p=" ".join(bad),
            )
        )

    for mouse, g in d.groupby("mouse"):
        g = g.reset_index(drop=True)
        geno = g.genotype.iloc[0]
        # what build_pairs("consecutive") generates
        for i in range(len(g) - 1):
            add("consecutive", mouse, geno, g.loc[i], g.loc[i + 1])
        # what build_pairs("transition") generates
        L, R = g[g.stage == "learning"], g[g.stage == "reversal"]
        if not L.empty and not R.empty:
            add("transition", mouse, geno, L.iloc[-1], R.iloc[0])
        # bridges: the consecutive chain over sessions that actually have suite2p
        ok = g[g.has_suite2p].reset_index(drop=True)
        expected = set(zip(g.date[:-1], g.date[1:]))
        for i in range(len(ok) - 1):
            a, b = ok.loc[i], ok.loc[i + 1]
            if (a.date, b.date) not in expected:
                add("bridge", mouse, geno, a, b)

    cov = pd.DataFrame(rows)
    # transition pairs that coincide with a consecutive pair are the same run
    cov = cov.drop_duplicates(subset=["mouse", "date_a", "date_b", "kind"])

    # match tables on disk that none of the above explain (e.g. --pairs-csv runs)
    known = set(zip(cov.mouse, cov.date_a, cov.date_b))
    extra = []
    for f in sorted(results.glob("matches_*.csv")):
        if f.name.startswith("._"):
            continue
        parts = f.stem[len("matches_") :].split("_")
        if len(parts) == 3 and tuple(parts) not in known:
            extra.append(dict(mouse=parts[0], date_a=parts[1], date_b=parts[2]))
    return d, cov, pd.DataFrame(extra)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument(
        "--dff",
        type=Path,
        default=paths.DFF,
        help="folder with {mouse}_{date}_stat/ops/iscell.npy "
        "(default: viral.nlgf.paths.DFF)",
    )
    ap.add_argument(
        "--results",
        type=Path,
        default=paths.RESULTS,
        help="folder with matches_*.csv (default: viral.nlgf.paths.RESULTS)",
    )
    ap.add_argument(
        "--min-cells",
        type=int,
        default=250,
        help="must match what build_pairs used (250)",
    )
    args = ap.parse_args()

    print(f"dff:     {args.dff}\nresults: {args.results}\n")
    if not args.dff.exists() or not args.results.exists():
        sys.exit("one of those folders does not exist - pass --dff / --results")

    sess, cov, extra = coverage(args.dff, args.results, args.min_cells)

    nos = sess[~sess.has_suite2p]
    print(f"{len(sess)} cohort sessions, {len(nos)} without suite2p files:")
    if len(nos):
        print(
            nos[["mouse", "genotype", "stage", "date", "missing_files"]].to_string(
                index=False
            )
        )

    print("\n=== pair status ===")
    print(pd.crosstab(cov.kind, cov.status).to_string())

    problems = cov[cov.status != "registered"]
    if len(problems):
        print("\n=== not registered ===")
        print(problems.sort_values(["mouse", "date_a"]).to_string(index=False))
    else:
        print("\nevery expected pair has a match table and a diagnostics row")

    if len(extra):
        print(
            f"\n{len(extra)} match tables outside the consecutive/transition/bridge "
            "sets (from --pairs-csv or --mode all runs):"
        )
        print(extra.to_string(index=False))

    out = args.results / "registration_coverage.csv"
    cov.to_csv(out, index=False)
    print(f"\nwritten {out}")


if __name__ == "__main__":
    main()
